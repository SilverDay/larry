//! SSH side of the transfer (see docs/spec.md, Connections and transfer security).
//!
//! Everything here produces text or commands for the system OpenSSH; nothing is reimplemented.
//! Host keys are pinned: no trust on first use.

use crate::Cmd;
use std::net::IpAddr;
use std::path::{Path, PathBuf};

fn plain(what: &str, v: &str) -> Result<(), String> {
    if v.is_empty() || v.chars().any(|c| c.is_whitespace() || c.is_control() || c == '"' || c == '\'') {
        return Err(format!("{what} '{v}' must not be empty or contain whitespace, quotes or control characters"));
    }
    Ok(())
}

fn abs_path(what: &str, v: &str) -> Result<(), String> {
    plain(what, v)?;
    if !v.starts_with('/') {
        return Err(format!("{what} '{v}' must be an absolute path"));
    }
    Ok(())
}

fn name_ok(what: &str, v: &str) -> Result<(), String> {
    if v.is_empty() || !v.bytes().all(|c| c.is_ascii_alphanumeric() || b"._-".contains(&c)) {
        return Err(format!("{what} '{v}' may only hold letters, digits, '.', '_' and '-'"));
    }
    Ok(())
}

/// The Host alias used in the generated ssh config.
pub fn alias(target: &str) -> String {
    format!("larry-{target}")
}

pub struct TargetSsh<'a> {
    pub name: &'a str,
    pub address: &'a str,
    pub user: &'a str,
    pub identity_file: &'a str,
}

/// OpenSSH refuses socket paths of 108 bytes or more, and while connecting it appends a 17-byte
/// temporary suffix to the ControlPath. `%C` expands to 40 characters. Longest usable directory:
pub const MAX_CONTROL_DIR: usize = 108 - 1 - "/cm-".len() - 40 - 17;

/// Generated by `init`: strict host-key checking against the tool's own known_hosts,
/// and connection sharing through an absolute ControlPath (a relative one failed).
/// `%C` is a fixed-length hash, so the socket path stays under the 108-byte limit.
pub fn ssh_config(targets: &[TargetSsh], known_hosts: &str, control_dir: &str) -> Result<String, String> {
    abs_path("known_hosts path", known_hosts)?;
    abs_path("control directory", control_dir)?;
    if control_dir.trim_end_matches('/').len() > MAX_CONTROL_DIR {
        return Err(format!(
            "control directory '{control_dir}' is too long: ssh refuses ControlPath socket paths of 108 bytes or more (at most {MAX_CONTROL_DIR} characters here); use a shorter directory"
        ));
    }
    let mut out = String::from("# Generated by `larry init`. Host keys are pinned in the known_hosts file below.\n");
    for t in targets {
        name_ok("target name", t.name)?;
        plain("address", t.address)?;
        name_ok("transfer user", t.user)?;
        abs_path("identity file", t.identity_file)?;
        out += &format!(
            "\nHost {}\n    HostName {}\n    User {}\n    IdentityFile {}\n    IdentitiesOnly yes\n    StrictHostKeyChecking yes\n    UserKnownHostsFile {}\n    ControlMaster auto\n    ControlPath {}/cm-%C\n    ControlPersist 10m\n",
            alias(t.name),
            t.address,
            t.user,
            t.identity_file,
            known_hosts,
            control_dir.trim_end_matches('/'),
        );
    }
    Ok(out)
}

/// `(key type, base64)` from a public key line, with or without a leading host field.
pub fn parse_key(line: &str) -> Result<(String, String), String> {
    let f: Vec<&str> = line.split_whitespace().collect();
    let i = f.iter().position(|w| w.starts_with("ssh-") || w.starts_with("ecdsa-") || w.starts_with("sk-")).ok_or("not a public key line")?;
    if f.len() < i + 2 {
        return Err("public key line has no key data".into());
    }
    Ok((f[i].to_string(), f[i + 1].to_string()))
}

/// SHA256 fingerprint of a public key, from the system `ssh-keygen`.
pub fn fingerprint(key_line: &str) -> Result<String, String> {
    let (t, b) = parse_key(key_line)?;
    let out = Cmd::new("ssh-keygen").args(["-l", "-f", "-"]).stdin_data(format!("{t} {b}\n")).run_checked().map_err(|e| e.to_string())?;
    out.stdout.split_whitespace().find(|w| w.starts_with("SHA256:")).map(String::from).ok_or_else(|| format!("unexpected ssh-keygen output: {}", out.stdout.trim()))
}

/// Read a target's host key with `ssh-keyscan`. The result is only a candidate: the admin must
/// compare its fingerprint with the one shown on the target's console before it is pinned.
pub fn scan_host_key(address: &str) -> Result<String, String> {
    plain("address", address)?;
    let out = Cmd::new("ssh-keyscan").args(["-t", "ed25519", "-T", "10"]).arg(address).run_checked().map_err(|e| e.to_string())?;
    out.stdout
        .lines()
        .find(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .map(String::from)
        .ok_or_else(|| format!("{address}: no ed25519 host key offered"))
}

/// The known_hosts line, but only if the key's fingerprint is the one the admin confirmed.
pub fn pin(address: &str, scanned_key: &str, confirmed_fingerprint: &str) -> Result<String, String> {
    plain("address", address)?;
    let actual = fingerprint(scanned_key)?;
    if actual != confirmed_fingerprint.trim() {
        return Err(format!("host key fingerprint {actual} does not match the confirmed {}: not pinned", confirmed_fingerprint.trim()));
    }
    let (t, b) = parse_key(scanned_key)?;
    Ok(format!("{address} {t} {b}"))
}

/// `authorized_keys` line for the transfer account: no shell, no forwarding, source address only,
/// and a forced `rrsync` that can only write below the drop directory.
pub fn authorized_keys_line(public_key: &str, source_ip: &str, incoming_dir: &str, rrsync: &str) -> Result<String, String> {
    let ip: IpAddr = source_ip.parse().map_err(|_| format!("'{source_ip}' is not an IP address"))?;
    abs_path("incoming directory", incoming_dir)?;
    abs_path("rrsync path", rrsync)?;
    let (t, b) = parse_key(public_key)?;
    Ok(format!("restrict,from=\"{ip}\",command=\"{rrsync} -wo {incoming_dir}\" {t} {b}"))
}

// ---------------------------------------------------------------- sshd

fn begin(target: &str) -> String {
    format!("# BEGIN larry:{target}")
}
fn end(target: &str) -> String {
    format!("# END larry:{target}")
}

/// Password-login fallback: refuse the transfer account from every address except the source.
/// `DenyUsers` accumulates, so it still works when an `Include` at the top of sshd_config has
/// already set other values (for most keywords the first value obtained wins). `Match all`
/// closes the block so later lines in the file are not captured by it.
pub fn sshd_block(target: &str, user: &str, source_ip: &str) -> Result<String, String> {
    name_ok("target name", target)?;
    name_ok("transfer user", user)?;
    let ip: IpAddr = source_ip.parse().map_err(|_| format!("'{source_ip}' is not an IP address"))?;
    Ok(format!("{}\nMatch User {user} Address *,!{ip}\n    DenyUsers {user}\nMatch all\n{}\n", begin(target), end(target)))
}

pub fn insert_block(config: &str, target: &str, block: &str) -> Result<String, String> {
    if config.contains(&begin(target)) {
        return Err(format!("sshd_config already holds a larry block for '{target}'"));
    }
    let mut out = config.to_string();
    if !out.is_empty() && !out.ends_with('\n') {
        out.push('\n');
    }
    out.push('\n');
    out += block;
    Ok(out)
}

/// Remove exactly the marked block (and the blank line before it). Returns false if there was none.
pub fn remove_block(config: &str, target: &str) -> Result<(String, bool), String> {
    let (b, e) = (begin(target), end(target));
    let lines: Vec<&str> = config.lines().collect();
    let Some(start) = lines.iter().position(|l| l.trim_end() == b) else { return Ok((config.to_string(), false)) };
    let Some(stop) = lines[start..].iter().position(|l| l.trim_end() == e).map(|p| p + start) else {
        return Err(format!("found '{b}' without a matching '{e}': not touching sshd_config"));
    };
    let mut from = start;
    if from > 0 && lines[from - 1].trim().is_empty() {
        from -= 1;
    }
    let mut out: Vec<&str> = lines[..from].to_vec();
    out.extend(&lines[stop + 1..]);
    Ok((out.join("\n") + "\n", true))
}

pub struct Sshd {
    pub binary: PathBuf,
    pub config: PathBuf,
}

impl Sshd {
    pub fn find(config: &Path) -> Result<Sshd, String> {
        let binary = crate::find_tool(&["sshd"])
            .map(PathBuf::from)
            .or_else(|| ["/usr/sbin/sshd", "/sbin/sshd"].iter().map(PathBuf::from).find(|p| p.is_file()))
            .ok_or("sshd not found")?;
        Ok(Sshd { binary, config: config.to_path_buf() })
    }

    pub fn test(&self) -> Result<(), String> {
        let out = Cmd::new(&self.binary).arg("-t").arg("-f").arg(&self.config).run().map_err(|e| e.to_string())?;
        if out.success() { Ok(()) } else { Err(format!("sshd -t failed: {}", out.stderr.trim())) }
    }

    /// Users denied for a connection from `addr`, from the effective configuration (`sshd -T -C`).
    pub fn denied_users(&self, user: &str, addr: &str) -> Result<Vec<String>, String> {
        name_ok("user", user)?;
        let _: IpAddr = addr.parse().map_err(|_| format!("'{addr}' is not an IP address"))?;
        let out = Cmd::new(&self.binary)
            .arg("-T")
            .arg("-f")
            .arg(&self.config)
            .arg("-C")
            .arg(format!("user={user},host=larry-check,addr={addr}"))
            .run_checked()
            .map_err(|e| e.to_string())?;
        Ok(out
            .stdout
            .lines()
            .filter_map(|l| l.strip_prefix("denyusers "))
            .flat_map(|l| l.split_whitespace().map(String::from).collect::<Vec<_>>())
            .collect())
    }

    /// The account must be refused from `other_addr` and allowed from `source_ip`.
    pub fn verify_restriction(&self, user: &str, source_ip: &str, other_addr: &str) -> Result<(), String> {
        if self.denied_users(user, source_ip)?.iter().any(|u| u == user) {
            return Err(format!("effective sshd config denies '{user}' from the source address {source_ip}"));
        }
        if !self.denied_users(user, other_addr)?.iter().any(|u| u == user) {
            return Err(format!("effective sshd config does not refuse '{user}' from {other_addr} (an earlier setting wins?)"));
        }
        Ok(())
    }
}

/// An address that is not the source, for the "denied" half of the check.
pub fn other_address(source_ip: &str) -> Result<String, String> {
    Ok(match source_ip.parse::<IpAddr>().map_err(|_| format!("'{source_ip}' is not an IP address"))? {
        IpAddr::V4(_) if source_ip != "203.0.113.77" => "203.0.113.77".into(),
        IpAddr::V4(_) => "203.0.113.78".into(),
        IpAddr::V6(_) if source_ip != "2001:db8::77" => "2001:db8::77".into(),
        IpAddr::V6(_) => "2001:db8::78".into(),
    })
}

/// `--apply`: back up sshd_config, write the marked block, run `sshd -t`, then check the effective
/// settings for the source address and for one other address. Any failure restores the backup.
/// Reloading sshd stays the admin's step.
pub fn apply_block(sshd: &Sshd, target: &str, user: &str, source_ip: &str, stamp: &str) -> Result<PathBuf, String> {
    let block = sshd_block(target, user, source_ip)?;
    let original = std::fs::read_to_string(&sshd.config).map_err(|e| format!("{}: {e}", sshd.config.display()))?;
    let updated = insert_block(&original, target, &block)?;
    let mut backup = sshd.config.as_os_str().to_owned();
    backup.push(format!(".larry-{stamp}.bak"));
    let backup = PathBuf::from(backup);
    if backup.exists() {
        return Err(format!("{} already exists: not overwriting a backup", backup.display()));
    }
    std::fs::copy(&sshd.config, &backup).map_err(|e| format!("backup {}: {e}", backup.display()))?;
    let restore = |why: String| -> String {
        match std::fs::copy(&backup, &sshd.config) {
            Ok(_) => format!("{why}; sshd_config restored from {}", backup.display()),
            Err(e) => format!("{why}; ALSO COULD NOT RESTORE {}: {e}", backup.display()),
        }
    };
    std::fs::write(&sshd.config, updated).map_err(|e| restore(e.to_string()))?;
    sshd.test().map_err(&restore)?;
    sshd.verify_restriction(user, source_ip, &other_address(source_ip)?).map_err(&restore)?;
    Ok(backup)
}

/// `cleanup`: back up sshd_config, remove exactly the marked block, run `sshd -t`; any failure
/// restores the backup. `None` means there was no block. Reloading sshd stays the admin's step.
pub fn remove_applied(sshd: &Sshd, target: &str, stamp: &str) -> Result<Option<PathBuf>, String> {
    let original = std::fs::read_to_string(&sshd.config).map_err(|e| format!("{}: {e}", sshd.config.display()))?;
    let (updated, removed) = remove_block(&original, target)?;
    if !removed {
        return Ok(None);
    }
    let mut backup = sshd.config.as_os_str().to_owned();
    backup.push(format!(".larry-{stamp}.bak"));
    let backup = PathBuf::from(backup);
    if backup.exists() {
        return Err(format!("{} already exists: not overwriting a backup", backup.display()));
    }
    std::fs::copy(&sshd.config, &backup).map_err(|e| format!("backup {}: {e}", backup.display()))?;
    std::fs::write(&sshd.config, updated).map_err(|e| format!("{}: {e}", sshd.config.display()))?;
    if let Err(e) = sshd.test() {
        let _ = std::fs::copy(&backup, &sshd.config);
        return Err(format!("{e}; sshd_config restored from {}", backup.display()));
    }
    Ok(Some(backup))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(n: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("larry-ssh-{n}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    fn keypair(dir: &Path, name: &str) -> (PathBuf, String) {
        let p = dir.join(name);
        Cmd::new("ssh-keygen").args(["-q", "-t", "ed25519", "-N", "", "-f"]).arg(&p).run_checked().unwrap();
        let pubkey = std::fs::read_to_string(dir.join(format!("{name}.pub"))).unwrap();
        (p, pubkey)
    }

    #[test]
    fn ssh_config_is_strict_and_absolute() {
        let t = [TargetSsh { name: "web1", address: "192.0.2.10", user: "migrate", identity_file: "/root/larry/id_ed25519" }];
        let c = ssh_config(&t, "/root/larry/known_hosts", "/root/larry/").unwrap();
        for want in ["Host larry-web1", "HostName 192.0.2.10", "StrictHostKeyChecking yes", "UserKnownHostsFile /root/larry/known_hosts", "ControlMaster auto", "ControlPath /root/larry/cm-%C", "IdentitiesOnly yes"] {
            assert!(c.contains(want), "missing {want}\n{c}");
        }
        assert!(ssh_config(&t, "known_hosts", "/x").is_err(), "relative path refused");
        assert!(ssh_config(&t, "/k", "~/.ssh").is_err());
        let long = format!("/{}", "d".repeat(MAX_CONTROL_DIR));
        assert!(ssh_config(&t, "/k", &long).unwrap_err().contains("too long"), "a ControlPath over 108 bytes breaks ssh and rsync");
        assert!(ssh_config(&t, "/k", &long[..MAX_CONTROL_DIR]).is_ok());
        let bad = [TargetSsh { name: "web1", address: "h\nProxyCommand evil", user: "m", identity_file: "/i" }];
        assert!(ssh_config(&bad, "/k", "/c").is_err(), "no option injection through values");
    }

    #[test]
    fn host_key_is_pinned_only_when_the_fingerprint_matches() {
        let d = tmp("pin");
        let (_, pubkey) = keypair(&d, "host");
        let fp = fingerprint(&pubkey).unwrap();
        assert!(fp.starts_with("SHA256:"));
        let scanned = format!("192.0.2.10 {}", pubkey.trim());
        assert_eq!(fingerprint(&scanned).unwrap(), fp, "leading host field is ignored");
        let line = pin("192.0.2.10", &scanned, &fp).unwrap();
        assert!(line.starts_with("192.0.2.10 ssh-ed25519 "));
        let (_, other) = keypair(&d, "evil");
        let err = pin("192.0.2.10", &format!("192.0.2.10 {}", other.trim()), &fp).unwrap_err();
        assert!(err.contains("does not match"), "{err}");
        assert!(pin("192.0.2.10", "garbage", &fp).is_err());
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn authorized_keys_line_is_restricted() {
        let d = tmp("ak");
        let (_, pubkey) = keypair(&d, "k");
        let l = authorized_keys_line(&pubkey, "192.0.2.1", "/srv/migration-incoming", "/usr/bin/rrsync").unwrap();
        assert!(l.starts_with("restrict,from=\"192.0.2.1\",command=\"/usr/bin/rrsync -wo /srv/migration-incoming\" ssh-ed25519 "), "{l}");
        assert!(!l.contains('\n') && !l.contains("comment"));
        assert!(authorized_keys_line(&pubkey, "not-an-ip", "/x", "/usr/bin/rrsync").is_err());
        assert!(authorized_keys_line(&pubkey, "192.0.2.1", "/srv/in coming", "/usr/bin/rrsync").is_err());
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn block_insert_and_remove_round_trip() {
        let cfg = "Port 22\nPasswordAuthentication yes\n";
        let block = sshd_block("web1", "migrate", "192.0.2.1").unwrap();
        let with = insert_block(cfg, "web1", &block).unwrap();
        assert!(with.contains("Match User migrate Address *,!192.0.2.1\n    DenyUsers migrate\nMatch all\n"));
        assert!(insert_block(&with, "web1", &block).is_err(), "no duplicate block");
        let (without, removed) = remove_block(&with, "web1").unwrap();
        assert!(removed);
        assert_eq!(without, cfg, "removal restores the file exactly");
        assert_eq!(remove_block(cfg, "web1").unwrap(), (cfg.to_string(), false));
        assert!(remove_block("# BEGIN larry:web1\nMatch all\n", "web1").is_err(), "unterminated block is left alone");
        assert!(sshd_block("web1", "mig rate", "192.0.2.1").is_err());
        assert_eq!(other_address("192.0.2.1").unwrap(), "203.0.113.77");
    }

    /// Against the real sshd: the effective config is checked for an allowed and a denied address,
    /// including the case where an Include at the top of sshd_config already set the first value.
    #[test]
    fn effective_config_is_verified_with_the_real_sshd() {
        let Ok(probe) = Sshd::find(Path::new("/dev/null")) else {
            eprintln!("SKIPPED: sshd not installed");
            return;
        };
        let d = tmp("sshd");
        let (hostkey, _) = keypair(&d, "hostkey");
        std::fs::write(d.join("extra.conf"), "PasswordAuthentication yes\n").unwrap();
        let base = format!("Include {}/extra.conf\nHostKey {}\nPort 2222\n", d.display(), hostkey.display());
        let cfg = d.join("sshd_config");
        std::fs::write(&cfg, &base).unwrap();
        let sshd = Sshd { binary: probe.binary, config: cfg.clone() };

        let backup = apply_block(&sshd, "web1", "migrate", "192.0.2.1", "20261119-120000").unwrap();
        assert_eq!(std::fs::read_to_string(&backup).unwrap(), base, "backup is the untouched original");
        assert_eq!(sshd.denied_users("migrate", "192.0.2.1").unwrap(), Vec::<String>::new());
        assert_eq!(sshd.denied_users("migrate", "203.0.113.9").unwrap(), ["migrate"]);
        assert!(sshd.denied_users("alice", "203.0.113.9").unwrap().is_empty(), "other accounts are unaffected");
        assert!(apply_block(&sshd, "web1", "migrate", "192.0.2.1", "20261119-120001").is_err(), "second apply refused");

        // a config sshd rejects is rolled back
        let broken = Sshd { binary: sshd.binary.clone(), config: d.join("broken_config") };
        std::fs::write(&broken.config, "HostKey /does/not/exist\nBogusOption yes\n").unwrap();
        let before = std::fs::read_to_string(&broken.config).unwrap();
        let err = apply_block(&broken, "web1", "migrate", "192.0.2.1", "20261119-120002").unwrap_err();
        assert!(err.contains("restored"), "{err}");
        assert_eq!(std::fs::read_to_string(&broken.config).unwrap(), before);

        // cleanup: block removed, original restored
        let with_block = std::fs::read_to_string(&cfg).unwrap();
        let backup = remove_applied(&sshd, "web1", "20261119-130000").unwrap().unwrap();
        assert_eq!(std::fs::read_to_string(&backup).unwrap(), with_block, "the backup holds the block, for rollback");
        assert_eq!(std::fs::read_to_string(&cfg).unwrap(), base);
        assert_eq!(remove_applied(&sshd, "web1", "20261119-130001").unwrap(), None, "nothing left to remove");
        assert!(sshd.denied_users("migrate", "203.0.113.9").unwrap().is_empty());
        std::fs::remove_dir_all(&d).unwrap();
    }
}
