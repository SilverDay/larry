//! larry-plan: turn `inventory.jsonl` into `sites.toml` (see docs/spec.md, Configuration).
//!
//! `plan` never overwrites a `sites.toml` that was edited after it was written:
//! it writes `sites.new.toml` and shows the diff instead. "Edited" is detected with
//! a hash of the generated body, kept in the first line of the file.

use larry_config::{is_db_name, MigrationConfig};
use larry_discover::{DbStatus, Record};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

const HEADER: &str = "# larry-plan: sha256=";

/// Answers recorded for sites that need a decision: `Some(name)` or `None` for "no database".
pub type Answers = BTreeMap<String, Option<String>>;

#[derive(Debug)]
pub struct Plan {
    /// Generated body, without the hash header.
    pub body: String,
    pub included: Vec<String>,
    /// (domain, reason): not written to sites.toml until decided.
    pub held_back: Vec<(String, String)>,
    pub skipped: Vec<(String, String)>,
}

fn q(s: &str) -> String {
    // TOML basic string
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn key(k: &str) -> String {
    if !k.is_empty() && k.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_' || c == b'-') {
        k.into()
    } else {
        q(k)
    }
}

/// Which target a site gets: the default one, or the only one.
fn pick_target(cfg: &MigrationConfig) -> Option<String> {
    cfg.default_target().map(String::from).or_else(|| (cfg.targets.len() == 1).then(|| cfg.targets.keys().next().cloned().unwrap()))
}

pub fn build(records: &[Record], cfg: &MigrationConfig, answers: &Answers) -> Result<Plan, String> {
    for (d, a) in answers {
        if let Some(n) = a {
            if !is_db_name(n) {
                return Err(format!("--db {d}={n}: not a plain database name"));
            }
        }
        if !records.iter().any(|r| &r.domain == d) {
            return Err(format!("--db {d}: not in the inventory (typo?)"));
        }
    }
    let target = pick_target(cfg);
    let mut recs: Vec<&Record> = records.iter().collect();
    recs.sort_by(|a, b| a.domain.cmp(&b.domain));

    let mut plan = Plan { body: String::new(), included: vec![], held_back: vec![], skipped: vec![] };
    let mut body = String::from("# Generated by `larry plan`. Edit freely: a later `larry plan` will not overwrite your edits.\n");
    for r in recs {
        if let Some(why) = &r.skip {
            plan.skipped.push((r.domain.clone(), why.clone()));
            continue;
        }
        let Some(target) = &target else {
            plan.held_back.push((r.domain.clone(), "several targets and no default: set `default = true` on one".into()));
            continue;
        };
        let db: Option<String> = match (r.db.status, answers.get(&r.domain)) {
            (_, Some(a)) => a.clone(),
            (DbStatus::Resolved, None) => r.db.name.clone(),
            (DbStatus::Absent, None) => None,
            (DbStatus::Unresolved, None) => {
                // Never written with an empty database: that would silently mean "no database".
                plan.held_back.push((r.domain.clone(), r.db.note.clone()));
                continue;
            }
        };

        body += "\n[[site]]\n";
        body += &format!("domain        = {}\n", q(&r.domain));
        body += &format!("target        = {}\n", q(target));
        body += &format!("docroot       = {}\n", q(r.docroot_name.as_deref().unwrap_or("public")));
        if let Some(db) = &db {
            body += &format!("db            = {}\n", q(db));
        }
        if !r.old_path_hits.is_empty() {
            body +=
                &format!("# {} PHP file(s) mention the old path {}; set true to rewrite them\n", r.old_path_hits.len(), r.vhost_root.as_deref().unwrap_or("?"));
        }
        body += "rewrite_paths = false\n";

        // php_* settings found in vhosts and .htaccess: proposed pool settings, for review
        let mut vals: BTreeMap<String, (String, String)> = BTreeMap::new();
        let mut flags: BTreeMap<String, (String, String)> = BTreeMap::new();
        let mut notes: Vec<String> = vec![];
        for s in &r.php_settings {
            let map = if s.kind.ends_with("flag") { &mut flags } else { &mut vals };
            match map.get(&s.name) {
                None => {
                    map.insert(s.name.clone(), (s.value.clone(), s.source.clone()));
                }
                Some((v, src)) if *v != s.value => notes.push(format!("# conflict for {}: {v} ({src}) kept, {} ({}) ignored", s.name, s.value, s.source)),
                _ => {}
            }
            if s.kind.starts_with("php_admin") {
                notes.push(format!(
                    "# {} was {}, which pool settings treat as php_{}",
                    s.name,
                    s.kind,
                    if s.kind.ends_with("flag") { "flag" } else { "value" }
                ));
            }
        }
        if !vals.is_empty() || !flags.is_empty() {
            body += "\n[site.fpm]\n";
            for n in &notes {
                body += &format!("{n}\n");
            }
            for (name, map) in [("php_value", &vals), ("php_flag", &flags)] {
                if !map.is_empty() {
                    body += &format!("\n[site.fpm.{name}]\n");
                    for (k, (v, src)) in map {
                        body += &format!("{} = {} # from {src}\n", key(k), q(v));
                    }
                }
            }
        }
        plan.included.push(r.domain.clone());
    }
    plan.body = body;
    Ok(plan)
}

fn sha(s: &str) -> String {
    Sha256::digest(s.as_bytes()).iter().map(|b| format!("{b:02x}")).collect()
}

fn norm(s: &str) -> String {
    s.replace("\r\n", "\n")
}

/// The file as written: hash header + body.
pub fn render(body: &str) -> String {
    format!("{HEADER}{}\n{body}", sha(&norm(body)))
}

/// True if `existing` carries a header whose hash still matches its body, i.e. nobody edited it.
pub fn is_untouched(existing: &str) -> bool {
    let text = norm(existing);
    let Some((first, rest)) = text.split_once('\n') else { return false };
    first.strip_prefix(HEADER).map(|h| h.trim() == sha(rest)).unwrap_or(false)
}

fn strip_header(s: &str) -> String {
    let s = norm(s);
    match s.split_once('\n') {
        Some((first, rest)) if first.starts_with(HEADER) => rest.to_string(),
        _ => s,
    }
}

#[derive(Debug, PartialEq)]
pub enum Written {
    Created(PathBuf),
    Updated(PathBuf),
    Unchanged(PathBuf),
    /// An edited sites.toml was left alone; the proposal is in `path`, with this diff.
    Diverted {
        path: PathBuf,
        diff: String,
    },
}

pub fn write_plan(sites_toml: &Path, plan: &Plan) -> Result<Written, String> {
    let new_text = render(&plan.body);
    let err = |p: &Path, e: std::io::Error| format!("{}: {e}", p.display());
    match std::fs::read_to_string(sites_toml) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            atomic(sites_toml, &new_text)?;
            Ok(Written::Created(sites_toml.into()))
        }
        Err(e) => Err(err(sites_toml, e)),
        Ok(existing) if existing == new_text => Ok(Written::Unchanged(sites_toml.into())),
        Ok(existing) if is_untouched(&existing) => {
            atomic(sites_toml, &new_text)?;
            Ok(Written::Updated(sites_toml.into()))
        }
        Ok(existing) => {
            let new_path = sites_toml.with_file_name("sites.new.toml");
            atomic(&new_path, &new_text)?;
            let diff = diff_lines(&strip_header(&existing), &plan.body);
            Ok(Written::Diverted { path: new_path, diff })
        }
    }
}

fn atomic(path: &Path, text: &str) -> Result<(), String> {
    let part = path.with_extension("toml.part");
    std::fs::write(&part, text).map_err(|e| format!("{}: {e}", part.display()))?;
    std::fs::rename(&part, path).map_err(|e| format!("{}: {e}", path.display()))
}

/// Line diff (longest common subsequence): `-` removed, `+` added, unchanged lines omitted.
pub fn diff_lines(old: &str, new: &str) -> String {
    let a: Vec<&str> = old.lines().collect();
    let b: Vec<&str> = new.lines().collect();
    let mut l = vec![vec![0usize; b.len() + 1]; a.len() + 1];
    for i in (0..a.len()).rev() {
        for j in (0..b.len()).rev() {
            l[i][j] = if a[i] == b[j] { l[i + 1][j + 1] + 1 } else { l[i + 1][j].max(l[i][j + 1]) };
        }
    }
    let (mut i, mut j, mut out) = (0, 0, String::new());
    while i < a.len() || j < b.len() {
        if i < a.len() && j < b.len() && a[i] == b[j] {
            i += 1;
            j += 1;
        } else if j < b.len() && (i == a.len() || l[i][j + 1] >= l[i + 1][j]) {
            out += &format!("+ {}\n", b[j]);
            j += 1;
        } else {
            out += &format!("- {}\n", a[i]);
            i += 1;
        }
    }
    out
}

pub fn summary(plan: &Plan) -> String {
    let mut o = format!("{} site(s) planned", plan.included.len());
    if !plan.held_back.is_empty() {
        o += &format!(", {} held back:\n", plan.held_back.len());
        for (d, why) in &plan.held_back {
            o += &format!("  {d}: {why}\n");
        }
    } else {
        o += "\n";
    }
    if !plan.skipped.is_empty() {
        o += &format!("{} skipped (no files to move):\n", plan.skipped.len());
        for (d, why) in &plan.skipped {
            o += &format!("  {d}: {why}\n");
        }
    }
    o
}

#[cfg(test)]
mod tests {
    use super::*;
    use larry_config::SitesFile;
    use larry_discover::{DbInfo, PathHit, PhpSetting};

    const CFG: &str = r#"
version = 1
[source]
db_defaults_file = "/root/migration-db.cnf"
[ssh]
config_file = "/root/larry/ssh_config"
known_hosts = "/root/larry/known_hosts"
[targets.web1]
host = "web1.example.net"
host_key = "SHA256:abc"
transfer_user = "migrate"
incoming_dir = "/srv/migration-incoming"
default = true
"#;

    fn rec(domain: &str, status: DbStatus, db: Option<&str>) -> Record {
        let mut r = Record::new(domain);
        r.docroot = Some(format!("/var/www/{domain}/httpdocs"));
        r.vhost_root = Some(format!("/var/www/{domain}"));
        r.docroot_name = Some("httpdocs".into());
        r.db = DbInfo { status, name: db.map(String::from), source: None, verified: true, note: "note".into(), candidates: Default::default() };
        r
    }

    #[test]
    fn generated_plan_loads_and_holds_back_unresolved() {
        let cfg = MigrationConfig::parse(CFG).unwrap();
        let mut shop = rec("shop.example.org", DbStatus::Resolved, Some("shop_db"));
        shop.php_settings = vec![
            PhpSetting { kind: "php_value".into(), name: "memory_limit".into(), value: "256M".into(), source: ".htaccess".into() },
            PhpSetting { kind: "php_admin_flag".into(), name: "session.use_strict_mode".into(), value: "on".into(), source: "vhost".into() },
        ];
        shop.old_path_hits = vec![PathHit { file: "a.php".into(), count: 2 }];
        let mut redir = Record::new("redir.example.org");
        redir.skip = Some("redirect-only".into());
        let records = vec![shop, rec("amb.example.org", DbStatus::Unresolved, None), rec("static.example.org", DbStatus::Absent, None), redir];

        let plan = build(&records, &cfg, &Answers::new()).unwrap();
        assert_eq!(plan.included, ["shop.example.org", "static.example.org"]);
        assert_eq!(plan.held_back[0].0, "amb.example.org");
        assert_eq!(plan.skipped[0].0, "redir.example.org");
        assert!(!plan.body.contains("amb.example.org"));

        // the generated file is valid input for the config crate
        let sites = SitesFile::parse(&render(&plan.body), &cfg).unwrap();
        assert_eq!(sites.site.len(), 2);
        let shop = &sites.site[0];
        assert_eq!(shop.db.as_deref(), Some("shop_db"));
        assert_eq!(shop.docroot.as_deref(), Some("httpdocs"));
        assert_eq!(shop.fpm.php_value["memory_limit"], "256M");
        assert_eq!(shop.fpm.php_flag["session.use_strict_mode"], "on");
        assert!(!shop.rewrite_paths);
        assert_eq!(sites.site[1].db, None);

        // a recorded answer releases the held-back site; an empty answer means "no database"
        let mut ans = Answers::new();
        ans.insert("amb.example.org".into(), Some("a_db".into()));
        let plan = build(&records, &cfg, &ans).unwrap();
        assert_eq!(plan.included.len(), 3);
        assert!(plan.held_back.is_empty());
        ans.insert("amb.example.org".into(), None);
        assert!(!build(&records, &cfg, &ans).unwrap().body.contains("db            = \"a_db\""));
        ans.insert("typo.example.org".into(), None);
        assert!(build(&records, &cfg, &ans).is_err());
    }

    #[test]
    fn edited_sites_toml_is_never_overwritten() {
        let cfg = MigrationConfig::parse(CFG).unwrap();
        let dir = std::env::temp_dir().join(format!("larry-plan-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("sites.toml");

        let p1 = build(&[rec("a.example.org", DbStatus::Absent, None)], &cfg, &Answers::new()).unwrap();
        assert!(matches!(write_plan(&path, &p1).unwrap(), Written::Created(_)));
        assert!(matches!(write_plan(&path, &p1).unwrap(), Written::Unchanged(_)));

        // untouched file: a changed inventory simply updates it
        let p2 = build(&[rec("a.example.org", DbStatus::Absent, None), rec("b.example.org", DbStatus::Absent, None)], &cfg, &Answers::new()).unwrap();
        assert!(matches!(write_plan(&path, &p2).unwrap(), Written::Updated(_)));

        // hand edit (CRLF editors included): now it is protected
        let edited = std::fs::read_to_string(&path).unwrap().replace("rewrite_paths = false", "rewrite_paths = true");
        std::fs::write(&path, &edited).unwrap();
        let p3 = build(&[rec("a.example.org", DbStatus::Absent, None)], &cfg, &Answers::new()).unwrap();
        match write_plan(&path, &p3).unwrap() {
            Written::Diverted { path: new, diff } => {
                assert!(new.ends_with("sites.new.toml"));
                assert!(diff.contains("- rewrite_paths = true") && diff.contains("+ rewrite_paths = false"));
                assert!(diff.contains("- domain        = \"b.example.org\""));
            }
            w => panic!("expected Diverted, got {w:?}"),
        }
        assert_eq!(std::fs::read_to_string(&path).unwrap(), edited, "the edited file is untouched");
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn diff_is_minimal() {
        assert_eq!(diff_lines("a\nb\nc\n", "a\nx\nc\n"), "+ x\n- b\n");
        assert_eq!(diff_lines("a\n", "a\n"), "");
    }
}
